"""Exp 08c — Assemble AraPromptBench v2 (final 1,000-prompt dataset).

Merges the 850 corpus-sourced prompts (08a) with the 150 synthetic creative
prompts (08b, generated by Claude Fable 5 — deliberately a different model
family from the gpt-4o-mini under test), validates everything, assigns ids,
and freezes a stratified 80/20 dev/test split (seed 42).

The whole v2 dataset is new material (zero overlap with the 500-prompt pilot,
enforced by normalised-text dedup), so the random stratified split is clean:
no pilot contamination can reach the test set.

Outputs:
  ../../AraPromptBench_v2.json      the frozen dataset
  results/qc_report.json            quality-control report
  results/inspection_sample.md      5% stratified sample for author review
"""

import json
import random
import re
import sys
import unicodedata
from collections import Counter
from datetime import date
from pathlib import Path

import tiktoken

SEED = 42
ENC = tiktoken.get_encoding("cl100k_base")
ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results"
PROJECT = ROOT.parent.parent
PILOT = PROJECT / "AraPromptBench_dataset.json"
OUT = PROJECT / "AraPromptBench_v2.json"

BANDS = {"short": (30, 90), "medium": (91, 250), "long": (251, 650)}
PREFIX = {"instruction": "inst", "summarisation": "summ", "qa": "qa",
          "creative": "creat"}
# creative briefs cap the *requested output*; the brief itself may sit outside
# the sourced bands (long briefs embed premises), so bands are recomputed and
# reported, not enforced, for creative
CAP_PATTERN = re.compile(r"كلم[ةت]|كلمات")


def norm(s: str) -> str:
    s = unicodedata.normalize("NFC", s)
    s = re.sub(r"[ً-ْـ]", "", s)
    s = re.sub(r"[^\w\s]", " ", s)
    return re.sub(r"\s+", " ", s).strip().lower()


def band_of(n: int) -> str:
    for b, (lo, hi) in BANDS.items():
        if lo <= n <= hi:
            return b
    return "long" if n > 650 else "sub-short"


def main() -> None:
    sourced = json.loads((RESULTS / "sourced_prompts.json")
                         .read_text(encoding="utf-8"))["prompts"]
    creative = []
    for part in sorted(ROOT.glob("creative_prompts_part*.json")):
        creative.extend(json.loads(part.read_text(encoding="utf-8")))
    print(f"sourced: {len(sourced)}, creative: {len(creative)}")
    assert len(creative) == 150, "creative must be exactly 150"

    issues = []
    rows = []
    for r in sourced:
        rows.append(dict(category=r["category"], prompt=r["prompt"],
                         source=r["source"], source_id=r["source_id"],
                         license=r["license"], variety=r["variety"],
                         subcategory=r["source"].lower(),
                         template_id=r.get("template_id"),
                         truncated=r.get("truncated", False)))
    for i, c in enumerate(creative):
        if not CAP_PATTERN.search(c["prompt"]):
            issues.append(f"creative #{i} missing output word-cap")
        rows.append(dict(category="creative", prompt=c["prompt"].strip(),
                         source="synthetic-claude", source_id=f"c{i+1:03d}",
                         license="CC BY 4.0",
                         variety="MSA", subcategory=c["form"],
                         template_id=None, truncated=False))

    # dedup within v2 and against pilot
    seen = {norm(p["prompt"]) for p in
            json.loads(PILOT.read_text(encoding="utf-8"))["prompts"]}
    n_pilot_keys = len(seen)
    kept = []
    for r in rows:
        k = norm(r["prompt"])
        if k in seen:
            issues.append(f"duplicate dropped: {r['source']}/{r['source_id']}")
            continue
        seen.add(k)
        kept.append(r)
    rows = kept

    for r in rows:
        r["token_count"] = len(ENC.encode(r["prompt"]))
        r["length_band"] = band_of(r["token_count"])

    # ids + stratified split
    rng = random.Random(SEED)
    final = []
    for cat in ["instruction", "summarisation", "qa", "creative"]:
        cat_rows = [r for r in rows if r["category"] == cat]
        rng.shuffle(cat_rows)
        n_test = round(len(cat_rows) * 0.20)
        for j, r in enumerate(cat_rows):
            r["id"] = f"v2-{PREFIX[cat]}-{j+1:03d}"
            r["split"] = "test" if j < n_test else "dev"
        # order by id for readability
        final.extend(sorted(cat_rows, key=lambda x: x["id"]))

    meta = {
        "name": "AraPromptBench",
        "version": "2.0.0",
        "created": str(date.today()),
        "description": "Final AraPromptBench dataset: 850 prompts sourced "
                       "from six public Arabic corpora (SDR Table 2) plus "
                       "150 synthetic creative prompts. All material is new "
                       "(zero overlap with the 500-prompt pilot); the "
                       "stratified 80/20 dev/test split is therefore free of "
                       "pilot contamination.",
        "language": "ar",
        "language_variety": "MSA with a 2% dialectal probe (Aya subset)",
        "categories": ["instruction", "summarisation", "qa", "creative"],
        "seed": SEED,
        "length_bands_cl100k": {k: list(v) for k, v in BANDS.items()},
        "sources": {
            "CIDAR": {"hf": "arbml/CIDAR", "license": "CC BY-NC 4.0"},
            "XL-Sum": {"hf": "csebuetnlp/xlsum (arabic)",
                       "license": "CC BY-NC-SA 4.0"},
            "EASC": {"hf": "arbml/easc", "license": "research-use"},
            "TyDi-QA": {"hf": "google-research-datasets/tydiqa (GoldP, arabic)",
                        "license": "Apache 2.0"},
            "ARCD": {"hf": "hsseinmz/arcd", "license": "CC BY-SA 4.0"},
            "Aya": {"hf": "CohereForAI/aya_dataset (arb + dialects)",
                    "license": "Apache 2.0"},
            "synthetic-claude": {
                "generator": "Claude Fable 5 (Anthropic), 2026-07",
                "license": "CC BY 4.0",
                "note": "Creative briefs written by an assistant model from a "
                        "different family than the LLM under test "
                        "(gpt-4o-mini) to avoid generator/evaluator "
                        "circularity. Every brief caps the requested output "
                        "length (max 120 words)."},
        },
        "deviations_from_sdr": [
            "ARCD 91 (pool exhausted after dedup/answerability); QA topped "
            "up to 250 from TyDi-QA (159).",
            "Creative prompts synthetic (Claude) rather than author-written; "
            "enables synthetic-vs-sourced robustness comparison.",
            "Aya split 80 MSA / 20 dialectal per proposal's 'limited "
            "dialectal inclusion'.",
        ],
        "total_prompts": len(final),
    }

    OUT.write_text(json.dumps({"metadata": meta, "prompts": final},
                              ensure_ascii=False, indent=1), encoding="utf-8")

    # ---- QC report ----------------------------------------------------------
    qc = {
        "total": len(final),
        "by_category": dict(Counter(r["category"] for r in final)),
        "by_split": dict(Counter(r["split"] for r in final)),
        "by_category_split": {f"{c}/{s}": n for (c, s), n in
                              Counter((r["category"], r["split"])
                                      for r in final).items()},
        "by_source": dict(Counter(r["source"] for r in final)),
        "by_variety": dict(Counter(r["variety"] for r in final)),
        "band_by_category": {c: dict(Counter(r["length_band"] for r in final
                                             if r["category"] == c))
                             for c in PREFIX},
        "token_count": {"min": min(r["token_count"] for r in final),
                        "median": sorted(r["token_count"]
                                         for r in final)[len(final)//2],
                        "max": max(r["token_count"] for r in final)},
        "duplicates_dropped_or_flagged": issues,
        "pilot_overlap": 0,
        "dialect_in_test": sum(1 for r in final if r["split"] == "test"
                               and r["variety"].startswith("dialect")),
    }
    RESULTS.joinpath("qc_report.json").write_text(
        json.dumps(qc, ensure_ascii=False, indent=2), encoding="utf-8")

    # ---- 5% inspection sample ----------------------------------------------
    rng2 = random.Random(SEED + 1)
    lines = ["# AraPromptBench v2 — 5% inspection sample (author review)\n",
             "Per the SDR QA plan: manually inspect each prompt below for "
             "fluency, task clarity, and category fit. Mark any problem and "
             "we regenerate/replace before the benchmark runs.\n"]
    for cat in PREFIX:
        sample = rng2.sample([r for r in final if r["category"] == cat], 13)
        lines.append(f"\n## {cat} (13 of {qc['by_category'][cat]})\n")
        for r in sample:
            lines.append(f"**{r['id']}** ({r['source']}, {r['length_band']}, "
                         f"{r['split']})\n\n> {r['prompt'][:600]}\n")
    RESULTS.joinpath("inspection_sample.md").write_text(
        "\n".join(lines), encoding="utf-8")

    print(json.dumps({k: v for k, v in qc.items()
                      if k != "duplicates_dropped_or_flagged"},
                     ensure_ascii=False, indent=2))
    print(f"issues: {len(issues)}")
    for i in issues[:10]:
        print(" ", i)
    print(f"\nSaved: {OUT}")
    print(f"QC: {RESULTS/'qc_report.json'}, sample: {RESULTS/'inspection_sample.md'}")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
